#!/usr/bin/env python3
"""Generate the app-level R class (canteenconnect.app.R) from aapt2 --emit-ids.

The app R is what lets Kotlin reference R.drawable.* resource ids. Library R
classes are generated by gen_r.py; this covers the app package only.

Input : OUT/ids.txt ("canteenconnect.app:drawable/foo = 0x7f...")
Output: OUT/gen/canteenconnect/app/R.java
"""
import os, re, sys

def main():
    base = sys.argv[1]                     # ccapp/build
    ids_path = os.path.join(base, "ids.txt")
    out_root = os.path.join(base, "gen", "canteenconnect", "app")
    os.makedirs(out_root, exist_ok=True)

    APP_PKG = "canteenconnect.app"
    by_type = {}
    with open(ids_path) as f:
        for line in f:
            m = re.match(r"\s*(\S+):(\w+)/(\S+)\s*=\s*(0x[0-9a-fA-F]+)", line)
            if m and m.group(1) == APP_PKG:
                by_type.setdefault(m.group(2), {})[m.group(3)] = m.group(4)

    lines = [
        "package canteenconnect.app;",
        "",
        "/* Generated by gen_appr.py — do not edit. */",
        "public final class R {",
        "    private R() {",
        "    }",
    ]
    for typ in sorted(by_type):
        fields = by_type[typ]
        lines.append(f"    public static final class {typ} {{")
        for name in sorted(fields):
            # aapt resource names may contain dots (e.g. TextAppearance.Compat.*);
            # Java field names must be [A-Za-z0-9_]. Sanitize deterministically.
            safe = "".join(ch if (ch.isalnum() or ch == "_") else "_" for ch in name)
            lines.append(f"        public static final int {safe} = {fields[name]};")
        lines.append("    }")
    lines.append("}")
    with open(os.path.join(out_root, "R.java"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"[R] app R class: {sum(len(v) for v in by_type.values())} ids across {len(by_type)} types")

if __name__ == "__main__":
    main()
